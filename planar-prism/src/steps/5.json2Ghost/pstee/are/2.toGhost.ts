const toActor = (actor: RawAreActorV10): GhostAreActor => ({
  name: actor.name,
  at: actor.at,
  destX: actor.destX,
  destY: actor.destY,
  flags: [...actor.flags],
  isSpawnedAsRandomMonster: actor.isSpawnedAsRandomMonster,
  creResrefLetter: actor.creResrefLetter,
  animation: actor.animation,
  direction: actor.direction,
  expiryTime: actor.expiryTime,
  wanderDistance: actor.wanderDistance,
  followDistance: actor.followDistance,
  presentedAt: [...actor.presentedAt],
  numTimesTalkedTo: actor.numTimesTalkedTo,
  dialog: actor.dialog,
  scriptOverride: actor.scriptOverride,
  scriptGeneral: actor.scriptGeneral,
  scriptClass: actor.scriptClass,
  scriptRace: actor.scriptRace,
  scriptDefault: actor.scriptDefault,
  scriptSpecifics: actor.scriptSpecifics,
  cre: actor.cre,
});

