export const toGhost = (raw: RawAre): GhostAre => ({
  resourceName: raw.resourceName,
  header: {
    signature: raw.header.signature,
    version: raw.header.version,
    wed: raw.header.wed,
    lastSaved: raw.header.lastSaved,
    flags: [...raw.header.flags],
    northAreaRef: raw.header.northAreaRef,
    northAreaFlags: [...raw.header.northAreaFlags],
    eastAreaRef: raw.header.eastAreaRef,
    eastAreaFlags: [...raw.header.eastAreaFlags],
    southAreaRef: raw.header.southAreaRef,
    southAreaFlags: [...raw.header.southAreaFlags],
    westAreaRef: raw.header.westAreaRef,
    westAreaFlags: [...raw.header.westAreaFlags],
    areaType: [...raw.header.areaType],
    rainProbability: raw.header.rainProbability,
    snowProbability: raw.header.snowProbability,
    fogProbability: raw.header.fogProbability,
    lightningProbability: raw.header.lightningProbability,
    overlayTransparency: raw.header.overlayTransparency,
    areaScript: raw.header.areaScript,
    restMovieDay: raw.header.restMovieDay,
    restMovieNight: raw.header.restMovieNight,
  },
  actors: raw.actors.map(toActor),
  regions: raw.regions.map(toRegion),
  spawnPoints: raw.spawnPoints.map(toSpawnPoint),
  entrances: raw.entrances.map(entrance => ({
    name: entrance.name,
    at: entrance.at,
    direction: entrance.direction,
  })),
  containers: raw.containers.map(toContainer),
  ambients: raw.ambients.map(toAmbient),
  variables: raw.variables.map(variable => ({
    name: variable.name,
    type: variable.type,
    resourceType: variable.resourceType,
    dwordValue: variable.dwordValue,
    intValue: variable.intValue,
    doubleValue: variable.doubleValue,
    scriptNameValue: variable.scriptNameValue,
  })),
  exploredBitmaskName: raw.exploredBitmaskName,
  doors: raw.doors.map(toDoor),
  animations: raw.animations.map(toAnimation),
  automapNotes: raw.automapNotes.map(note => ({
    at: note.at,
    textRef: note.textRef,
    strrefLocation: note.strrefLocation,
    markerColor: note.markerColor,
    controlId: note.controlId,
  })),
  tiledObjects: raw.tiledObjects.map(toTiledObject),
  projectileTraps: raw.projectileTraps.map(trap => ({
    projectile: trap.projectile,
    missileId: trap.missileId,
    ticksUntilCheck: trap.ticksUntilCheck,
    triggersRemaining: trap.triggersRemaining,
    x: trap.x,
    y: trap.y,
    z: trap.z,
    enemyAlly: trap.enemyAlly,
    indexOfPartyMemberWhoCreatedIt: trap.indexOfPartyMemberWhoCreatedIt,
  })),
  song: isNothing(raw.song)
    ? raw.song
    : {
        daySong: raw.song.daySong,
        nightSong: raw.song.nightSong,
        winSong: raw.song.winSong,
        battleSong: raw.song.battleSong,
        loseSong: raw.song.loseSong,
        altMusic1: raw.song.altMusic1,
        altMusic2: raw.song.altMusic2,
        altMusic3: raw.song.altMusic3,
        altMusic4: raw.song.altMusic4,
        altMusic5: raw.song.altMusic5,
        mainDayAmbient1: raw.song.mainDayAmbient1,
        mainDayAmbient2: raw.song.mainDayAmbient2,
        mainDayAmbientVolume: raw.song.mainDayAmbientVolume,
        mainNightAmbient1: raw.song.mainNightAmbient1,
        mainNightAmbient2: raw.song.mainNightAmbient2,
        mainNightAmbientVolume: raw.song.mainNightAmbientVolume,
        reverb: raw.song.reverb,
      },
  restInterruptions: isNothing(raw.restInterruptions)
    ? raw.restInterruptions
    : toRestInterruptions(raw.restInterruptions),
});
